import { test, expect, type APIRequestContext, type Page } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { spawnSync } from "node:child_process";
import { MESSAGES, MIN_SECONDS } from "../../src/data/signup";

// The "Get involved" sign-up, end to end, against `wrangler dev --env test`: the Worker in
// worker/index.ts with a local D1 in .wrangler/test-state (see playwright.config.ts).
//
// Every test sends its own CF-Connecting-IP, which wrangler dev passes through (Cloudflare
// sets it itself in production), so the five-a-minute rate limit applies per test.

const run = `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 6)}`;
let n = 0;
const ip = () => `10.${Math.floor(Math.random() * 250)}.${Math.floor(Math.random() * 250)}.${++n}`;
const email = (label: string) => `${label}-${run}@example.com`;

/** Reads the local test database. Values are generated by the tests, so inlining is safe. */
function rows(where: string): Record<string, string | number | null>[] {
  const args = ["wrangler", "d1", "execute", "breakbondsar-signups", "--local", "--env", "test", "--persist-to", ".wrangler/test-state", "--json", "--command", `SELECT * FROM signups WHERE ${where}`];
  const win = process.platform === "win32";
  const r = spawnSync("npx", win ? args.map((a) => `"${a}"`) : args, { shell: win, encoding: "utf8" });
  const out = r.stdout ?? "";
  if (r.status !== 0) throw new Error(`d1 execute failed: ${r.stderr || out}`);
  return JSON.parse(out.slice(out.indexOf("[")))[0].results;
}

async function token(request: APIRequestContext, headers: Record<string, string>): Promise<string> {
  const html = await (await request.get("/take-action/", { headers })).text();
  return html.match(/name="t" value="([^"]+)"/)![1];
}

/** Posts the form as a browser would, and returns where the Worker sends it. */
async function post(request: APIRequestContext, fields: Record<string, string>, opts: { wait?: boolean; ip?: string } = {}) {
  const headers = { "CF-Connecting-IP": opts.ip ?? ip() };
  const t = await token(request, headers);
  if (opts.wait !== false) await new Promise((r) => setTimeout(r, MIN_SECONDS * 1000 + 300));
  const res = await request.post("/api/signup", { form: { t, hp_extra: "", ...fields }, headers, maxRedirects: 0 });
  expect(res.status()).toBe(303);
  return res.headers()["location"];
}

const waitOut = (page: Page) => page.waitForTimeout(MIN_SECONDS * 1000 + 300);

for (const width of [375, 1280]) {
  test(`the form renders at ${width} px with no axe violations or outside requests`, async ({ page, baseURL }) => {
    await page.setViewportSize({ width, height: width < 768 ? 812 : 800 });
    const outside: string[] = [];
    const errors: string[] = [];
    page.on("request", (r) => {
      if (!r.url().startsWith("data:") && new URL(r.url()).origin !== new URL(baseURL!).origin) outside.push(r.url());
    });
    page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
    await page.goto("/take-action/#get-involved", { waitUntil: "networkidle" });

    const form = page.locator("#signup-form");
    await expect(form).toBeVisible();
    for (const label of ["Name", "Email", "Phone (optional)", "ZIP code (optional)", "Anything else? (optional)"]) {
      await expect(page.getByLabel(label, { exact: true })).toBeVisible();
    }
    await expect(page.getByRole("group", { name: "How do you want to help? (optional)" }).getByRole("checkbox")).toHaveCount(5);
    await expect(page.getByRole("button", { name: "Sign up" })).toBeVisible();
    await expect(form.getByRole("link", { name: "Read how they are stored" })).toHaveAttribute("href", "/privacy/#signup-title");
    await expect(page.locator("#signup-extra")).not.toBeInViewport();

    // Every control is at least 44 px tall. A checkbox's target is its whole label.
    const small = await page.$$eval("#signup-form :is(input:not([type=hidden], [type=checkbox], #signup-extra), textarea, button, label:has(input[type=checkbox]))", (els) =>
      els.filter((e) => e.getBoundingClientRect().height < 44).map((e) => e.outerHTML.slice(0, 80)),
    );
    expect(small).toEqual([]);

    const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
    expect(overflow).toBeLessThanOrEqual(0);

    for (const path of ["/take-action/", "/take-action/thanks/"]) {
      await page.goto(path, { waitUntil: "networkidle" });
      const axe = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21a", "wcag21aa", "wcag22aa", "best-practice"]).analyze();
      expect(axe.violations.map((v) => `${path} ${v.id}: ${v.nodes.map((x) => x.target.join(" ")).join(", ")}`)).toEqual([]);
    }
    expect(outside).toEqual([]);
    expect(errors).toEqual([]);
  });
}

test.describe("without JavaScript", () => {
  test.use({ javaScriptEnabled: false });

  test("a sign-up is stored and lands on the thank-you page", async ({ page }) => {
    await page.setExtraHTTPHeaders({ "CF-Connecting-IP": ip() });
    const address = email("nojs");
    await page.goto("/take-action/#get-involved");
    await page.getByLabel("Name", { exact: true }).fill("  Test   Signup ");
    await page.getByLabel("Email", { exact: true }).fill(address.toUpperCase());
    await page.getByLabel("Phone (optional)").fill("(501) 555-0134");
    await page.getByLabel("ZIP code (optional)").fill("72201");
    await page.getByLabel("Show up to actions").check();
    await page.getByLabel("Research and records").check();
    await page.getByLabel("Anything else? (optional)").fill("I can help on weekends.\nAnd evenings.");
    await waitOut(page);
    await page.getByRole("button", { name: "Sign up" }).click();

    await expect(page).toHaveURL(/\/take-action\/thanks\/$/);
    await expect(page.locator("h1")).toContainText("Thank you.");

    const [row, ...more] = rows(`email = '${address}'`);
    expect(more).toEqual([]);
    expect(row).toMatchObject({
      name: "Test Signup",
      email: address,
      phone: "+15015550134",
      zip: "72201",
      interests: "show-up,research",
      note: "I can help on weekends.\nAnd evenings.",
      source: "/take-action/",
    });
    expect(row.created_at).toMatch(/^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$/);
    expect(row.user_agent_hash).toMatch(/^[0-9a-f]{32}$/);
    expect(Object.keys(row).sort()).toEqual(
      ["created_at", "email", "id", "interests", "name", "note", "phone", "source", "updated_at", "user_agent_hash", "zip"].sort(),
    );
  });

  test("the browser stops an empty or malformed form before it is sent", async ({ page }) => {
    await page.goto("/take-action/#get-involved");
    await page.getByRole("button", { name: "Sign up" }).click();
    await expect(page).toHaveURL(/\/take-action\/#get-involved$/);
    await page.getByLabel("Name", { exact: true }).fill("Someone");
    await page.getByLabel("Email", { exact: true }).fill("not an address");
    await page.getByRole("button", { name: "Sign up" }).click();
    await expect(page).toHaveURL(/\/take-action\/#get-involved$/);
  });

  test("a problem the browser misses comes back as a message tied to its field", async ({ page }) => {
    await page.setExtraHTTPHeaders({ "CF-Connecting-IP": ip() });
    await page.goto("/take-action/#get-involved");
    await page.getByLabel("Name", { exact: true }).fill("Someone");
    // Valid to the browser (no dot in the domain), not to the Worker.
    await page.getByLabel("Email", { exact: true }).fill("someone@localhost");
    await waitOut(page);
    await page.getByRole("button", { name: "Sign up" }).click();

    await expect(page).toHaveURL(/\/take-action\/\?signup=error&e=email#get-involved$/);
    const alert = page.locator("#signup-alert");
    await expect(alert).toBeVisible();
    await expect(alert.getByRole("link", { name: MESSAGES.email })).toHaveAttribute("href", "#signup-email");
    const field = page.getByLabel("Email", { exact: true });
    await expect(field).toHaveAttribute("aria-invalid", "true");
    await expect(field).toHaveAccessibleDescription(MESSAGES.email);
    await expect(page.getByLabel("Name", { exact: true })).not.toHaveAttribute("aria-invalid", "true");
    expect(rows("email = 'someone@localhost'")).toEqual([]);
  });
});

test("the server names every invalid field and keeps nothing", async ({ request }) => {
  const location = await post(request, { name: "", email: "x", phone: "12", zip: "7220", note: "n".repeat(501) });
  expect(new URL(location).search).toBe("?signup=error&e=name,email,phone,zip,note");
  expect(rows("email = 'x'")).toEqual([]);
});

test("the honeypot is rejected without telling the sender", async ({ request }) => {
  const address = email("honeypot");
  const location = await post(request, { name: "Bot", email: address, hp_extra: "https://example.com" });
  expect(new URL(location).pathname).toBe("/take-action/thanks/");
  expect(rows(`email = '${address}'`)).toEqual([]);
});

test(`a form sent within ${MIN_SECONDS} seconds is rejected`, async ({ request }) => {
  const address = email("fast");
  const location = await post(request, { name: "Fast", email: address }, { wait: false });
  expect(new URL(location).search).toBe("?signup=error&e=form");
  expect(rows(`email = '${address}'`)).toEqual([]);
});

test("a forged or missing timestamp is rejected", async ({ request }) => {
  const address = email("forged");
  const headers = { "CF-Connecting-IP": ip() };
  for (const t of ["", "1700000000." + "0".repeat(64)]) {
    const res = await request.post("/api/signup", { form: { t, name: "Forged", email: address }, headers, maxRedirects: 0 });
    expect(new URL(res.headers()["location"]).search).toBe("?signup=error&e=form");
  }
  expect(rows(`email = '${address}'`)).toEqual([]);
});

test("a second sign-up with the same email updates the first row", async ({ request }) => {
  const address = email("dup");
  expect(await post(request, { name: "First Name", email: address, phone: "501-555-0100", zip: "72201", interests: "research" })).toMatch(/\/thanks\/$/);
  const [first] = rows(`email = '${address}'`);
  await new Promise((r) => setTimeout(r, 1100));
  expect(await post(request, { name: "Second Name", email: address.toUpperCase(), zip: "72202", note: "Updated." })).toMatch(/\/thanks\/$/);

  const all = rows(`email = '${address}'`);
  expect(all).toHaveLength(1);
  expect(all[0]).toMatchObject({
    id: first.id,
    created_at: first.created_at,
    name: "Second Name",
    phone: "+15015550100", // left blank the second time, so kept
    zip: "72202",
    interests: "research",
    note: "Updated.",
  });
  expect(String(all[0].updated_at) > String(first.created_at)).toBe(true);
});

test("more than five attempts a minute from one address are turned away", async ({ request }) => {
  const from = ip();
  const headers = { "CF-Connecting-IP": from };
  const outcomes: string[] = [];
  for (let i = 0; i < 6; i++) {
    const res = await request.post("/api/signup", { form: { t: "", name: "R", email: "r@example.com" }, headers, maxRedirects: 0 });
    outcomes.push(new URL(res.headers()["location"]).search);
  }
  expect(outcomes.slice(0, 5)).toEqual(Array(5).fill("?signup=error&e=form"));
  expect(outcomes[5]).toBe("?signup=error&e=busy");
});

test("the endpoint takes only same-origin POSTs", async ({ request }) => {
  const get = await request.get("/api/signup", { maxRedirects: 0 });
  expect(get.status()).toBe(303);
  expect(new URL(get.headers()["location"]).pathname).toBe("/take-action/");
  const foreign = await request.post("/api/signup", { form: { name: "x" }, headers: { Origin: "https://example.org" }, maxRedirects: 0 });
  expect(foreign.status()).toBe(403);
  expect((await request.get("/api/other", { maxRedirects: 0 })).status()).toBe(404);
});

test("with JavaScript, mistakes show inline before anything is sent", async ({ page }) => {
  const sent: string[] = [];
  page.on("request", (r) => r.method() === "POST" && sent.push(r.url()));
  await page.goto("/take-action/#get-involved", { waitUntil: "networkidle" });
  await page.getByLabel("Phone (optional)").fill("12");
  await page.getByRole("button", { name: "Sign up" }).click();

  const alert = page.locator("#signup-alert");
  await expect(alert).toBeVisible();
  await expect(alert).toBeFocused();
  await expect(alert.getByRole("listitem")).toHaveText([MESSAGES.name, MESSAGES.email, MESSAGES.phone]);
  await expect(page.getByLabel("Name", { exact: true })).toHaveAccessibleDescription(MESSAGES.name);
  await expect(page.getByLabel("Phone (optional)")).toHaveAttribute("aria-invalid", "true");
  await expect(page.getByLabel("Phone (optional)")).toHaveValue("12");

  // Fixing a field clears its message at once.
  await page.getByLabel("Name", { exact: true }).fill("Someone");
  await expect(page.getByLabel("Name", { exact: true })).not.toHaveAttribute("aria-invalid", "true");
  await expect(page.locator("#name-error")).toHaveText("");

  await alert.getByRole("link", { name: MESSAGES.email }).click();
  await expect(page.getByLabel("Email", { exact: true })).toBeFocused();
  expect(sent).toEqual([]);
});

